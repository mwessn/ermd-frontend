import { mysqlTypes } from "@/types/TableColumnTypes/mysqlTypes.ts";
import { postgresTypes } from "@/types/TableColumnTypes/postgresTypes.ts";

const PRIMITIVE_TYPES = [
    'int',
    'bigint', // For frontend handling
    'serial',
    'decimal', 'float', 'bit', 'bool',
    'char', 'string', 'binary',
    'date', 'time', 'datetime', 'interval',
    'list', 'json', 'enum', 'list enum',
];

export type PrimitiveColumnType = typeof PRIMITIVE_TYPES[number];

export const intervalValues = [
    'YEAR',
    'MONTH',
    'DAY',
    'HOUR',
    'MINUTE',
    'SECOND',
    'YEAR TO MONTH',
    'DAY TO HOUR',
    'DAY TO MINUTE',
    'DAY TO SECOND',
    'HOUR TO MINUTE',
    'HOUR TO SECOND',
    'MINUTE TO SECOND',
];

export const DatabaseEngines = [
    'mysql',
    'postgres',
    'mssql',
    'sqlite'
];

export type ModifierMeta = 'typeSelect' | // Render as column type dropdown selector
                            'inputNumber' | // Render as number input (for values that could be undefined)
                            'enumList' | // Render as enum values list
                            'typedef'; // Render as type definition input

export type DatabaseEngine = typeof DatabaseEngines[number];

export interface ColumnTypeModifier {
    readonly defaultValue: number | string | undefined;
    readonly hint: string;

    readonly minValue: number | undefined;
    readonly maxValue: number | undefined;

    readonly optional?: boolean;
    readonly meta?: ModifierMeta;
}

export interface ColumnType {
    readonly displayName: string;
    readonly primitive: PrimitiveColumnType;
    readonly modifier: ColumnTypeModifier[] | undefined;
    readonly flags: ColumnTypeFlags;
    // Aliases for automatic conversion between engines
    readonly alias: Record<DatabaseEngine, string | undefined>
}

export function getDefaultModifierParams(col: ColumnType) {
    if (!col.modifier) { return undefined }

    return col.modifier.map(it =>
        it.defaultValue
    );
}

interface ColumnTypeFlags {
    readonly canBePrimaryKey: boolean;
    readonly canAutoIncrement: boolean;

    // Includes datetime CURRENT values
    readonly canBeAutoGenerated: boolean;

    // Array of functions that can be used as default value
    readonly canHaveDefault: boolean;
    readonly defaultValues: Array<string> | undefined;

    // Minimum and maximum value for applicable columns
    readonly minValue: number | bigint | undefined;
    readonly maxValue: number | bigint | undefined;
}

export const defaultPrimaryTypes: Record<DatabaseEngine, ColumnType> = {
    mysql: mysqlTypes['INT'],
    postgres: postgresTypes['UUID'],
    mssql: mysqlTypes['INT'],
    sqlite: mysqlTypes['INT']
}